class TaskAssistError(RuntimeError):
    """Content-free error code safe for the host."""


def _uuid(value: object) -> str:
    if not isinstance(value, str) or not _UUID_RE.fullmatch(value):
        raise TaskAssistError("assist_request_id_invalid")
    try:
        if str(uuid.UUID(value)) != value:
            raise ValueError
    except ValueError:
        raise TaskAssistError("assist_request_id_invalid") from None
    return value


def _date(value: object) -> date:
    if type(value) is not date:
        raise TaskAssistError("assist_date_invalid")
    return value


def _decimal(env: Mapping[str, str], key: str, default: str, *, maximum: Decimal) -> Decimal:
    try:
        value = Decimal(str(env.get(key, default)))
    except (InvalidOperation, TypeError, ValueError):
        raise TaskAssistError("assist_configuration_invalid") from None
    if not value.is_finite() or value < 0 or value > maximum:
        raise TaskAssistError("assist_configuration_invalid")
    return value


def _micro(value: Decimal) -> int:
    return int((value * Decimal(1_000_000)).to_integral_value(rounding=ROUND_CEILING))


def _safe_digest(value: object) -> str:
    try:
        encoded = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":")).encode("utf-8")
    except (TypeError, ValueError, UnicodeError, RecursionError):
        raise TaskAssistError("assist_request_invalid") from None
    return hashlib.sha256(encoded).hexdigest()


def _strict_payload(payload: object, required: set[str], optional: set[str]) -> dict[str, Any]:
    if (
        not isinstance(payload, dict) or not required <= payload.keys()
        or not payload.keys() <= required | optional
    ):
        raise TaskAssistError("assist_request_invalid")
    return payload


def _clean_message(value: object) -> str:
    if not isinstance(value, str) or not value.strip() or len(value) > MAX_INPUT_CHARS:
        raise TaskAssistError("assist_input_invalid")
    try:
        return _text(value, MAX_INPUT_CHARS, paragraph=False)
    except TaskError:
        raise TaskAssistError("assist_input_not_permitted") from None


def _usage(value: object) -> tuple[int, int]:
    if (
        not isinstance(value, dict) or set(value) != {"input_tokens", "output_tokens"}
        or type(value["input_tokens"]) is not int or value["input_tokens"] < 0
        or type(value["output_tokens"]) is not int or value["output_tokens"] < 0
    ):
        raise TaskAssistError("assist_model_usage_invalid")
    if value["input_tokens"] > 100_000 or value["output_tokens"] > 20_000:
        raise TaskAssistError("assist_model_usage_invalid")
    return value["input_tokens"], value["output_tokens"]


def _validate_model(raw: object, expected_intent: str | None) -> tuple[dict[str, Any], int, int]:
    if not isinstance(raw, dict) or set(raw) != set(GENERATE_RESULT_SCHEMA["required"]):
        raise TaskAssistError("assist_model_output_invalid")
    if (
        raw["intent"] not in INTENTS
        or (expected_intent is not None and raw["intent"] != expected_intent)
        or not isinstance(raw["reply"], str) or len(raw["reply"]) > 1200
        or raw["language"] not in RESULT_LANGUAGES
        or not isinstance(raw["suggestions"], list) or len(raw["suggestions"]) > 4
        or any(not isinstance(item, str) or len(item) > 180 for item in raw["suggestions"])
        or (raw["task_path"] is not None and not task_path(raw["task_path"]))
        or (raw["changes"] is not None and not isinstance(raw["changes"], dict))
        or (raw["definition"] is not None and not isinstance(raw["definition"], dict))
        or (raw["scope"] is not None and (not isinstance(raw["scope"], str) or len(raw["scope"]) > 500))
        or (raw["estimate"] is not None and (
            not isinstance(raw["estimate"], dict)
            or set(raw["estimate"]) != {"minutes_low", "minutes_high", "rationale", "confidence"}
            or type(raw["estimate"]["minutes_low"]) is not int
            or type(raw["estimate"]["minutes_high"]) is not int
            or not 0 <= raw["estimate"]["minutes_low"] <= raw["estimate"]["minutes_high"] <= 10000
            or not isinstance(raw["estimate"]["rationale"], str) or len(raw["estimate"]["rationale"]) > 500
            or raw["estimate"]["confidence"] not in {"low", "medium", "high"}
        ))
        or (raw["plan"] is not None and (
            not isinstance(raw["plan"], dict) or set(raw["plan"]) != {"steps", "total_estimate_min"}
            or not isinstance(raw["plan"]["steps"], list) or len(raw["plan"]["steps"]) > 6
            or type(raw["plan"]["total_estimate_min"]) is not int
            or not 0 <= raw["plan"]["total_estimate_min"] <= 60000
            or any(
                not isinstance(item, dict) or set(item) != {"text", "estimate_min", "who"}
                or not isinstance(item["text"], str) or len(item["text"]) > 300
                or type(item["estimate_min"]) is not int or not 0 <= item["estimate_min"] <= 10000
                or item["who"] not in {"owner", "assistant", "agent"}
                for item in raw["plan"]["steps"]
            )
        ))
        or raw["knowledge_target"] not in {None, "learning", "wiki-candidate"}
    ):
        raise TaskAssistError("assist_model_output_invalid")
    if raw["completion"] is not None and (
        not isinstance(raw["completion"], dict)
        or set(raw["completion"]) != {"result", "evidence", "learning"}
        or not isinstance(raw["completion"]["result"], str) or len(raw["completion"]["result"]) > 1000
        or not isinstance(raw["completion"]["evidence"], str) or len(raw["completion"]["evidence"]) > 1000
        or (raw["completion"]["learning"] is not None and (
            not isinstance(raw["completion"]["learning"], str) or len(raw["completion"]["learning"]) > 1000
        ))
    ):
        raise TaskAssistError("assist_model_output_invalid")
    if raw["plan"] is not None and sum(
        item["estimate_min"] for item in raw["plan"]["steps"]
    ) != raw["plan"]["total_estimate_min"]:
        raise TaskAssistError("assist_model_output_invalid")
    try:
        if raw["changes"] is None:
            changes = None
        elif not isinstance(raw["changes"], dict) or raw["changes"].keys() - _CHANGE_PROPERTIES.keys():
            raise TaskError("assist_model_output_invalid")
        else:
            supplied = {key: value for key, value in raw["changes"].items() if value is not None}
            date_fields = {key: supplied.pop(key) for key in ("deadline", "focus_on") if key in supplied}
            changes = validate_changes(supplied) if supplied else {}
            for key, value in date_fields.items():
                if not isinstance(value, str) or not re.fullmatch(r"\d{4}-\d{2}-\d{2}", value):
                    raise TaskError("assist_model_output_invalid")
                try:
                    date.fromisoformat(value)
                except ValueError:
                    raise TaskError("assist_model_output_invalid") from None
                changes[key] = value
        if raw["definition"] is None:
            definition = None
        elif not isinstance(raw["definition"], dict) or raw["definition"].keys() - _CREATE_PROPERTIES.keys():
            raise TaskError("assist_model_output_invalid")
        else:
            definition = validate_changes(
                {key: value for key, value in raw["definition"].items() if value is not None}, create=True,
            )
    except TaskError:
        raise TaskAssistError("assist_model_output_invalid") from None
    try:
        input_tokens, output_tokens = _usage(raw["usage"])
    except TaskAssistError:
        raise
    result = {key: copy.deepcopy(raw[key]) for key in ASSIST_MODEL_SCHEMA["required"]}
    result["changes"] = changes
    result["definition"] = definition
    values_to_check = [result["reply"], *result["suggestions"]]
    if result["estimate"] is not None:
        values_to_check.append(result["estimate"]["rationale"])
    if result["plan"] is not None:
        values_to_check.extend(item["text"] for item in result["plan"]["steps"])
    for item in values_to_check:
        try:
            _text(item, max(1, len(item)), paragraph=True)
        except TaskError:
            raise TaskAssistError("assist_model_output_invalid") from None
    return result, input_tokens, output_tokens


class TaskAssist:
    """Assist API core; all content stays in the private bounded assist sidecar."""

    def __init__(
        self,
        service: Any,
        env: Mapping[str, str],
        generate: Callable[[dict[str, Any]], dict[str, Any]],
        transcribe: Callable[[bytes, str], dict[str, Any]] | None = None,
        *,
        store: AssistStore | None = None,
    ) -> None:
        if not callable(generate) or (transcribe is not None and not callable(transcribe)):
            raise TaskAssistError("assist_model_not_configured")
        self.service = service
        self.env = env
        self.generate = generate
        self.transcribe = transcribe
        self.store = store if store is not None else AssistStore.for_task_service(service)
        self.enabled = str(env.get("MINDME_ASSIST_ENABLED", "")).strip().lower() in {"1", "true", "yes"}
        self.auto_apply = str(env.get("MINDME_ASSIST_AUTO_APPLY", "true")).strip().lower() in {"1", "true", "yes"}
        try:
            budget = Decimal(str(env.get("MINDME_ASSIST_MONTHLY_EUR", "12")))
        except (InvalidOperation, ValueError, TypeError):
            raise TaskAssistError("assist_configuration_invalid") from None
        if not budget.is_finite() or not Decimal("0") < budget <= Decimal("20"):
            raise TaskAssistError("assist_configuration_invalid")
        self.monthly_budget = budget
        self.daily_soft_cap = budget / Decimal(20)
        self.input_price = DEFAULT_MODEL_INPUT_EUR_PER_1M
        self.output_price = DEFAULT_MODEL_OUTPUT_EUR_PER_1M
        self.transcription_price = _decimal(
            env, "MINDME_ASSIST_TRANSCRIPTION_EUR_PER_MINUTE", "0.006", maximum=Decimal(10),
        )
        if min(self.input_price, self.output_price, self.transcription_price) <= 0:
            raise TaskAssistError("assist_configuration_invalid")
        self.max_output_tokens = self._max_output_tokens(env)
        self.models = {
            "assist": env.get("MINDME_ASSIST_MODEL", "gpt-6-luna"),
            "planner": env.get("MINDME_ASSIST_PLANNER_MODEL", env.get("MINDME_ASSIST_PLANNER", "gpt-6-sol")),
            "orchestrator": env.get(
                "MINDME_ASSIST_ORCHESTRATOR_MODEL", env.get("MINDME_ASSIST_ORCHESTRATOR", "gpt-6-sol"),
            ),
        }
        if any(not isinstance(value, str) or not value or len(value) > 100 for value in self.models.values()):
            raise TaskAssistError("assist_configuration_invalid")
        self.model_prices = self._model_prices(env)
        self.transcription_model = env.get(
            "MINDME_ASSIST_TRANSCRIPTION_MODEL", "gpt-4o-mini-transcribe",
        )
        if not isinstance(self.transcription_model, str) or not self.transcription_model or len(self.transcription_model) > 100:
            raise TaskAssistError("assist_configuration_invalid")

    def _model_prices(self, env: Mapping[str, str]) -> dict[str, tuple[Decimal, Decimal]]:
        try:
            configured = json.loads(env.get(MODEL_PRICE_CONFIG_ENV, "{}"))
        except (TypeError, ValueError, json.JSONDecodeError):
            raise TaskAssistError("assist_configuration_invalid") from None
        if not isinstance(configured, dict) or configured.keys() - set(self.models.values()):
            raise TaskAssistError("assist_configuration_invalid")
        prices: dict[str, tuple[Decimal, Decimal]] = {}
        for model in set(self.models.values()):
            item = configured.get(model, {})
            if not isinstance(item, dict) or set(item) - {"input_eur_per_1m", "output_eur_per_1m"}:
                raise TaskAssistError("assist_configuration_invalid")
            try:
                input_price = Decimal(str(item.get("input_eur_per_1m", self.input_price)))
                output_price = Decimal(str(item.get("output_eur_per_1m", self.output_price)))
            except (InvalidOperation, ValueError, TypeError):
                raise TaskAssistError("assist_configuration_invalid") from None
            if (
                not input_price.is_finite() or not output_price.is_finite()
                or input_price <= 0 or output_price <= 0 or input_price > 1000 or output_price > 1000
            ):
                raise TaskAssistError("assist_configuration_invalid")
            prices[model] = (input_price, output_price)
        return prices

    @staticmethod
    def _max_output_tokens(env: Mapping[str, str]) -> int:
        try:
            value = int(env.get("MINDME_ASSIST_MAX_OUTPUT_TOKENS", str(MAX_OUTPUT_TOKENS)))
        except (TypeError, ValueError):
            raise TaskAssistError("assist_configuration_invalid") from None
        if not 128 <= value <= 4000:
            raise TaskAssistError("assist_configuration_invalid")
        return value

    def _owner_today(self, supplied: date) -> date:
        _date(supplied)
        try:
            owner_date = self.service.owner_date()
        except (AttributeError, TaskError):
            owner_date = supplied
        if type(owner_date) is not date:
            raise TaskAssistError("assist_date_invalid")
        return owner_date

    @staticmethod
    def _model_for(mode: str, action: str | None, message: str) -> str:
        if mode == "step" and action in {"plan", "resolve", "learn"}:
            return "planner"
        if mode == "chat" and re.search(
            r"(?iu)\b(plan|planning|analy[sz]e|break\s+down|roadmap|estimate|compare|strategy)\b"
            r"|(?:план|спланируй|разбей|оцени|сравни|стратег)", message,
        ):
            return "orchestrator"
        return "assist"

    def _reserve_micro(
        self, *, voice: bool, model: str | None = None, audio_seconds: float = 120,
    ) -> int:
        if voice:
            return _micro(Decimal(str(audio_seconds)) / Decimal(60) * self.transcription_price)
        input_tokens = 100000
        output_tokens = self.max_output_tokens
        input_price, output_price = self.model_prices[model or self.models["assist"]]
        reserve = (
            Decimal(input_tokens) * input_price / Decimal(1_000_000)
            + Decimal(output_tokens) * output_price / Decimal(1_000_000)
        )
        return _micro(reserve)

    def _claim(
        self, identifier: str, digest: str, thread_id: str | None, today: date, *,
        voice: bool, model: str | None = None, audio_seconds: float = 120,
        create_thread: bool = True,
    ) -> tuple[str, dict[str, Any] | None]:
        key = request_key(identifier)
        reserve = self._reserve_micro(voice=voice, model=model, audio_seconds=audio_seconds)
        monthly_cap = _micro(self.monthly_budget)
        resolved_thread = thread_id or str(uuid.uuid4())

        def claim(state: dict[str, Any]) -> tuple[str, dict[str, Any] | None]:
            prune_assist_state(state, today)
            previous = state["requests"].get(key)
            if previous:
                if previous["digest"] != digest:
                    raise TaskAssistError("assist_request_conflict")
                if previous["status"] == "recorded":
                    if voice and previous["response"] is None:
                        raise TaskAssistError("assist_request_uncertain")
                    return previous["thread_id"], copy.deepcopy(previous["response"])
                raise TaskAssistError("assist_request_uncertain")
            if thread_id is not None and thread_id not in state["threads"]:
                raise TaskAssistError("assist_thread_not_found")
            if len(state["requests"]) >= MAX_REQUESTS:
                raise TaskAssistError("assist_request_capacity")
            if create_thread and thread_id is None and len(state["threads"]) >= 40:
                raise TaskAssistError("assist_thread_capacity")
            ledger = state["ledger"]
            month_history = ledger.setdefault("month_history", {})
            day_history = ledger.setdefault("day_history", {})
            month = today.strftime("%Y-%m")
            day = today.isoformat()
            if ledger["month"] != month:
                old_month = ledger["month"]
                if old_month:
                    month_history[old_month] = {
                        "spent_micro_eur": ledger["spent_micro_eur"],
                        "reserved_micro_eur": ledger["reserved_micro_eur"],
                        "input_tokens": ledger["input_tokens"],
                        "output_tokens": ledger["output_tokens"],
                    }
                restored_month = month_history.pop(month, None) or {}
                ledger.update(
                    month=month,
                    spent_micro_eur=restored_month.get("spent_micro_eur", 0),
                    reserved_micro_eur=restored_month.get("reserved_micro_eur", 0),
                    input_tokens=restored_month.get("input_tokens", 0),
                    output_tokens=restored_month.get("output_tokens", 0),
                )
            if ledger["day"] != day:
                old_day = ledger["day"]
                if old_day:
                    day_history[old_day] = {
                        "daily_spent_micro_eur": ledger["daily_spent_micro_eur"],
                        "daily_reserved_micro_eur": ledger["daily_reserved_micro_eur"],
                    }
                restored_day = day_history.pop(day, None) or {}
                ledger.update(
                    day=day,
                    daily_spent_micro_eur=restored_day.get("daily_spent_micro_eur", 0),
                    daily_reserved_micro_eur=restored_day.get("daily_reserved_micro_eur", 0),
                )
            if ledger["spent_micro_eur"] + ledger["reserved_micro_eur"] + reserve > monthly_cap:
                raise TaskAssistError("assist_monthly_budget_exhausted")
            ledger["reserved_micro_eur"] += reserve
            ledger["daily_reserved_micro_eur"] += reserve
            if create_thread and thread_id is None:
                state["threads"][resolved_thread] = {"created_on": day, "last_on": day, "turns": []}
            state["requests"][key] = {
                "digest": digest, "status": "claimed", "created_on": day,
                "thread_id": resolved_thread, "response": None, "reserved_micro_eur": reserve,
                "accounting_month": month, "accounting_day": day,
            }
            return resolved_thread, None

        return self.store.update(claim)

    def _settle(
        self, identifier: str, today: date, *, input_tokens: int, output_tokens: int,
        model: str | None = None,
        billed_input_tokens: int | None = None, billed_output_tokens: int | None = None,
        audio_seconds: float = 0,
    ) -> None:
        input_price, output_price = self.model_prices.get(
            model or self.models["assist"], (self.input_price, self.output_price),
        )
        actual = (
            Decimal(input_tokens if billed_input_tokens is None else billed_input_tokens)
            * input_price / Decimal(1_000_000)
            + Decimal(output_tokens if billed_output_tokens is None else billed_output_tokens)
            * output_price / Decimal(1_000_000)
            + Decimal(str(audio_seconds)) / Decimal(60) * self.transcription_price
        )
        actual_micro = _micro(actual)
        key = request_key(identifier)

        def settle(state: dict[str, Any]) -> None:
            record = state["requests"].get(key)
            if not record or record["status"] != "claimed":
                raise TaskAssistError("assist_request_uncertain")
            ledger = state["ledger"]
            reserved = record["reserved_micro_eur"]
            accounting_month = record.get("accounting_month", record["created_on"][:7])
            accounting_day = record.get("accounting_day", record["created_on"])
            if ledger["month"] == accounting_month:
                month_bucket = ledger
            else:
                month_bucket = ledger.get("month_history", {}).get(accounting_month)
            if ledger["day"] == accounting_day:
                day_bucket = ledger
            else:
                day_bucket = ledger.get("day_history", {}).get(accounting_day)
            if month_bucket is None or day_bucket is None:
                raise TaskAssistError("assist_accounting_period_unavailable")
            month_bucket["reserved_micro_eur"] = max(
                0, month_bucket["reserved_micro_eur"] - reserved,
            )
            month_bucket["spent_micro_eur"] += actual_micro
            month_bucket["input_tokens"] += input_tokens
            month_bucket["output_tokens"] += output_tokens
            day_bucket["daily_reserved_micro_eur"] = max(
                0, day_bucket["daily_reserved_micro_eur"] - reserved,
            )
            day_bucket["daily_spent_micro_eur"] += actual_micro
            record["reserved_micro_eur"] = 0

        self.store.update(settle)

    @staticmethod
    def _invalidate_thread_responses(
        state: dict[str, Any], thread_id: str, current_record: dict[str, Any],
    ) -> None:
        for prior in state["requests"].values():
            if (
                prior is not current_record and prior["thread_id"] == thread_id
                and prior["status"] == "recorded" and prior["response"] is not None
            ):
                prior["response"] = None
                prior["status"] = "uncertain"

    def _finish(
        self, identifier: str, today: date, thread_id: str, message: str,
        response: dict[str, Any], task_refs: dict[str, str] | None = None,
    ) -> None:
        key = request_key(identifier)

        def finish(state: dict[str, Any]) -> None:
            record = state["requests"].get(key)
            if not record or record["status"] != "claimed" or record["thread_id"] != thread_id:
                raise TaskAssistError("assist_request_uncertain")
            thread = state["threads"].get(thread_id)
            if not thread:
                raise TaskAssistError("assist_thread_not_found")
            response_copy = copy.deepcopy(response)
            encoded = json.dumps(response_copy, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
            if len(encoded) > 8000:
                raise TaskAssistError("assist_response_too_large")
            refs = thread.setdefault("task_refs", {})
            new_revisions = task_refs or {}
            applied = any(
                isinstance(card, dict) and card.get("kind") == "applied" and card.get("saved") is True
                for card in response_copy.get("cards", [])
            )
            invalidate_responses = applied or any(
                path in refs and refs[path] != revision
                for path, revision in new_revisions.items()
            )
            if invalidate_responses:
                self._invalidate_thread_responses(state, thread_id, record)
                thread["turns"] = []
                refs.clear()
            if not applied:
                thread["turns"].append({"user": message, "assistant": response["reply"]})
                thread["turns"] = thread["turns"][-MAX_TURNS:]
            thread["last_on"] = today.isoformat()
            if task_refs:
                refs.update(task_refs)
                if len(refs) > 12:
                    thread["turns"] = [] if applied else thread["turns"][-1:]
                    refs.clear()
                    refs.update(task_refs)
            retain_guard = any(
                isinstance(card, dict) and card.get("kind") == "applied" and card.get("saved") is not True
                for card in response_copy.get("cards", [])
            )
            record["status"] = "uncertain" if retain_guard else "recorded"
            record["response"] = None if retain_guard else response_copy

        self.store.update(finish)

    def _claim_deterministic(
        self, identifier: str, digest: str, today: date, thread_id: str | None = None,
    ) -> tuple[str, dict[str, Any] | None]:
        key = request_key(identifier)
        resolved_thread = thread_id or str(uuid.uuid4())

        def claim(state: dict[str, Any]) -> tuple[str, dict[str, Any] | None]:
            prune_assist_state(state, today)
            previous = state["requests"].get(key)
            if previous:
                if previous["digest"] != digest:
                    raise TaskAssistError("assist_request_conflict")
                if previous["status"] == "recorded":
                    return previous["thread_id"], copy.deepcopy(previous["response"])
                raise TaskAssistError("assist_request_uncertain")
            if thread_id is not None and thread_id not in state["threads"]:
                raise TaskAssistError("assist_thread_not_found")
            if len(state["requests"]) >= MAX_REQUESTS:
                raise TaskAssistError("assist_request_capacity")
            if thread_id is None:
                if len(state["threads"]) >= 40:
                    raise TaskAssistError("assist_thread_capacity")
                state["threads"][resolved_thread] = {
                    "created_on": today.isoformat(), "last_on": today.isoformat(), "turns": [],
                }
            state["requests"][key] = {
                "digest": digest, "status": "claimed", "created_on": today.isoformat(),
                "thread_id": resolved_thread, "response": None, "reserved_micro_eur": 0,
            }
            return resolved_thread, None

        return self.store.update(claim)

    def _finish_deterministic(
        self, identifier: str, response: dict[str, Any],
        task_ref: dict[str, str] | None = None,
    ) -> None:
        key = request_key(identifier)

        def finish(state: dict[str, Any]) -> None:
            record = state["requests"].get(key)
            if not record or record["status"] != "claimed":
                raise TaskAssistError("assist_request_uncertain")
            encoded = json.dumps(response, ensure_ascii=False, separators=(",", ":")).encode("utf-8")
            if len(encoded) > 8000:
                raise TaskAssistError("assist_response_too_large")
            record["status"] = "recorded"
            record["response"] = copy.deepcopy(response)
            thread = state["threads"].get(record["thread_id"])
            if thread and task_ref:
                refs = thread.setdefault("task_refs", {})
                changed = task_ref["path"] in refs and refs[task_ref["path"]] != task_ref["revision"]
                if changed:
                    self._invalidate_thread_responses(state, record["thread_id"], record)
                    thread["turns"] = []
                    refs.clear()
                refs[task_ref["path"]] = task_ref["revision"]
                if len(refs) > 12:
                    thread["turns"] = []
                    refs.clear()
                    refs[task_ref["path"]] = task_ref["revision"]
                thread["last_on"] = record["created_on"]

        self.store.update(finish)

    def _finish_voice(self, identifier: str) -> None:
        key = request_key(identifier)

        def finish(state: dict[str, Any]) -> None:
            record = state["requests"].get(key)
            if not record or record["status"] != "claimed":
                raise TaskAssistError("assist_request_uncertain")
            record["status"] = "uncertain"
            record["response"] = None

        self.store.update(finish)

    def _mark_uncertain(self, identifier: str) -> None:
        key = request_key(identifier)

        def mark(state: dict[str, Any]) -> None:
            record = state["requests"].get(key)
            if record and record["status"] == "claimed":
                record["status"] = "uncertain"

        try:
            self.store.update(mark)
        except AssistStoreError:
            pass

    def _source_context(self, path: str | None, revision: str | None = None) -> list[dict[str, Any]]:
        sources = []
        # The contract is a schema document, not a task inventory.
        try:
            contract = self.service._source("tasks/README.md")
        except (SourceError, TaskError):
            contract = None
        if isinstance(contract, dict) and isinstance(contract.get("text"), str):
            text = contract["text"]
            if len(text) <= MAX_CONTEXT_CHARS:
                sources.append({
                    "path": "tasks/README.md", "revision": contract["revision"], "text": text,
                    "kind": "task_contract",
                })
        if path is not None:
            if not task_path(path):
                raise TaskAssistError("assist_task_path_invalid")
            try:
                source = self.service._source(path, revision)
            except (TaskError, SourceError) as error:
                raise TaskAssistError(str(error)) from None
            except Exception:
                raise TaskAssistError("assist_source_unavailable") from None
            if not isinstance(source, dict) or not isinstance(source.get("text"), str):
                raise TaskAssistError("assist_source_unavailable")
            text = source["text"]
            if len(text) > MAX_CONTEXT_CHARS:
                raise TaskAssistError("assist_source_too_large")
            sources.append({
                "path": source["path"], "revision": source["revision"],
                "text": text, "kind": "canonical_task",
            })
        if sum(len(item["text"]) for item in sources) > MAX_CONTEXT_CHARS:
            sources = sources[-1:]
        return sources

    def _overview_candidates(self, today: date) -> list[dict[str, Any]]:
        repository = getattr(self.service, "repository", None)
        if repository is None or not hasattr(repository, "page"):
            return []
        try:
            page = repository.page(0, today=today)
        except (SourceError, TaskError):
            raise TaskAssistError("assist_overview_unavailable") from None
        items = page.get("items") if isinstance(page, dict) else None
        if not isinstance(items, list):
            raise TaskAssistError("assist_overview_unavailable")
        candidates = []
        for item in items:
            if not isinstance(item, dict) or item.get("attention_eligible") is not True:
                continue
            path, revision = item.get("path"), item.get("revision")
            if not task_path(path) or not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
                continue
            candidates.append({
                key: item[key] for key in (
                    "path", "revision", "title", "stage", "area", "project", "execution",
                    "deadline", "review_on", "attention_reasons", "attention_eligible",
                ) if key in item
            })
            if len(candidates) == 3:
                break
        return [
            {"rank": index + 1, **candidate}
            for index, candidate in enumerate(candidates)
        ]

    def _recheck_thread(self, thread_id: str) -> bool:
        state = self.store.read()
        thread = state["threads"].get(thread_id)
        if not thread:
            raise TaskAssistError("assist_thread_not_found")
        refs = thread.get("task_refs")
        if thread["turns"] and refs is None:
            current = False
        else:
            current = True
            for path, revision in (refs or {}).items():
                try:
                    self.service._source(path, revision)
                except (TaskError, SourceError):
                    current = False
                    break
        if current:
            return True

        def invalidate(updated: dict[str, Any]) -> None:
            target = updated["threads"].get(thread_id)
            if target:
                target["turns"] = []
                target["task_refs"] = {}
            for request in updated["requests"].values():
                if request["thread_id"] != thread_id or not isinstance(request["response"], dict):
                    continue
                previous = request["response"]
                request["response"] = {
                    "thread_id": thread_id,
                    "reply": "The task source changed, so earlier context was cleared. Please restate what you need.",
                    "language": previous.get("language") if previous.get("language") in RESULT_LANGUAGES else "en",
                    "cards": [], "suggestions": [],
                    **({"usage": previous["usage"]} if isinstance(previous.get("usage"), dict) else {}),
                }

        self.store.update(invalidate)
        return False

    def _cached_thread_response(
        self, identifier: str, thread_id: str, cached: dict[str, Any], today: date,
    ) -> dict[str, Any]:
        if self._recheck_thread(thread_id):
            return cached
        refreshed = self.store.read()["requests"].get(request_key(identifier), {}).get("response")
        if isinstance(refreshed, dict):
            return refreshed
        return {
            "thread_id": thread_id,
            "reply": "The task source changed, so earlier context was cleared. Please restate what you need.",
            "language": "en", "cards": [], "suggestions": [], "usage": self.usage(today),
        }

    def _generate(
        self, *, mode: str, action: str | None, message: str, language: str,
        thread_id: str, today: date, task_path_value: str | None,
        task_revision: str | None, model: str, candidates: list[dict[str, Any]],
    ) -> tuple[dict[str, Any], int, int]:
        state = self.store.read()
        thread = state["threads"].get(thread_id, {})
        turns = copy.deepcopy(thread.get("turns", []))[-MAX_TURNS:]
        sources = self._source_context(task_path_value, task_revision)
        context = {
            **GENERATE_CONTEXT_CONTRACT,
            "mode": mode,
            "action": action,
            "message": message,
            "language": language,
            "today": today.isoformat(),
            "thread": turns,
            "sources": sources,
            "candidates": candidates,
            "models": self.models,
            "model": self.models[model],
            "schema": ASSIST_MODEL_SCHEMA,
            "limits": {
                "input_chars": MAX_INPUT_CHARS, "output_tokens": self.max_output_tokens,
                "thread_turns": MAX_TURNS, "source_chars": MAX_CONTEXT_CHARS,
            },
        }
        model_input = {key: value for key, value in context.items() if key not in {"model", "schema"}}
        while len(json.dumps(model_input, ensure_ascii=False)) > 24000 and turns:
            turns.pop(0)
            context["thread"] = turns
            model_input["thread"] = turns
        if len(json.dumps(model_input, ensure_ascii=False)) > 24000 and len(sources) > 1:
            sources = sources[-1:]
            context["sources"] = sources
            model_input["sources"] = sources
        if len(json.dumps(model_input, ensure_ascii=False)) > 24000:
            raise TaskAssistError("assist_context_limit")
        try:
            raw = self.generate(context)
        except TaskAssistError:
            raise
        except Exception:
            raise TaskAssistError("assist_model_unavailable") from None
        return _validate_model(raw, action)

    @staticmethod
    def _explicit_done(message: str) -> bool:
        return bool(_DONE_RE.search(message))

    @staticmethod
    def _date_autoapply_allowed(value: dict[str, Any], message: str, owner_today: date) -> bool:
        for key in ("focus_on", "review_on"):
            proposed = value.get(key)
            if proposed is not None:
                try:
                    if date.fromisoformat(proposed) < owner_today:
                        return False
                except (TypeError, ValueError):
                    return False
        deadline = value.get("deadline")
        if deadline is None:
            return True
        try:
            parsed = date.fromisoformat(deadline)
        except (TypeError, ValueError):
            return False
        text = message.casefold()
        explicit = (
            deadline in message
            and re.search(r"(?iu)(deadline|due|by|дедлайн|срок|до)\b", message) is not None
        )
        expected = None
        if re.search(r"(?iu)(?:by|due|deadline)\s+today\b|(?:срок|до)\s+сегодня\b", text):
            expected = owner_today
        elif re.search(r"(?iu)(?:by|due|deadline)\s+tomorrow\b|(?:срок|до)\s+завтра\b", text):
            expected = owner_today + timedelta(days=1)
        relative = expected is not None and parsed == expected
        return explicit or relative

    def _operation(
        self, item: dict[str, Any], *, identifier: str, today: date, thread_id: str,
        owner_today: date, message: str, intent: str, source_revision: str | None,
    ) -> dict[str, Any] | None:
        path = item["task_path"]
        request_id = identifier.replace("-", "")
        if intent == "capture":
            definition = item["definition"]
            if not isinstance(definition, dict):
                raise TaskAssistError("assist_capture_invalid")
            definition = copy.deepcopy(definition)
            estimate = item.get("estimate")
            if isinstance(estimate, dict):
                low, high = estimate["minutes_low"], estimate["minutes_high"]
                estimate_text = (
                    f"Estimate: ~{low}m" if low == high
                    else f"Estimate: {low}–{high}m"
                )
                existing_context = definition.get("context", "")
                combined_context = (
                    f"{existing_context.rstrip()}\n{estimate_text}"
                    if existing_context else estimate_text
                )
                if len(combined_context) <= _TEXT_FIELDS["context"]:
                    definition["context"] = combined_context
            plan = item.get("plan")
            if isinstance(plan, dict):
                original_subtasks = list(definition.get("subtasks", []))
                subtasks = list(original_subtasks)
                for step in plan["steps"]:
                    text = step["text"]
                    if text not in subtasks and len(subtasks) < 6:
                        subtasks.append(text)
                if subtasks != original_subtasks:
                    definition["subtasks"] = subtasks
            try:
                proposal = self.service.capture({
                    "request_id": request_id, "text": message, "definition": definition,
                }, today)
            except (TaskError, SourceError) as error:
                raise TaskAssistError(str(error)) from None
            return self._proposal(
                proposal, thread_id, today, message,
                allow_autoapply=self._date_autoapply_allowed(definition, message, owner_today),
            )
        if intent in {"execute", "detail", "next", "change", "refine"} and path:
            if not isinstance(item["changes"], dict) or not item["changes"]:
                return None
            changes = copy.deepcopy(item["changes"])
            if not _EXPLICIT_CHANGE.search(message):
                return None
            accepted = set(EDIT_FIELDS) | {"deadline", "focus_on"}
            if changes.keys() - accepted:
                unsupported = ", ".join(sorted(changes.keys() - accepted))
                return {
                    "type": "draft", "kind": "draft", "title": "Change not prepared",
                    "action": "refine",
                    "body": f"TaskService does not accept these source-bound edit fields: {unsupported}. No change was prepared.",
                    "saved": False, "undo_available": False,
                }
            if {"review_on", "waiting_for"} & changes.keys() and "stage" not in changes:
                return {
                    "type": "draft", "kind": "draft", "title": "Waiting-state change not prepared",
                    "action": "refine",
                    "body": "TaskService requires a stage change with review_on or waiting_for. No change was prepared.",
                    "saved": False, "undo_available": False,
                }
            if ({"deadline", "focus_on"} & changes.keys()) and len(changes) > 1:
                unsupported = ", ".join(sorted({"deadline", "focus_on"} & changes.keys()))
                return {
                    "type": "draft", "kind": "draft", "title": "Mixed date change not prepared",
                    "action": "refine",
                    "body": f"TaskService only supports one date field per change; it cannot combine {unsupported} with other fields in one proposal. No change was prepared.",
                    "saved": False, "undo_available": False,
                }
            allow_autoapply = self._date_autoapply_allowed(changes, message, owner_today)
            try:
                if len(changes) == 1 and set(changes) <= {"deadline", "focus_on", "review_on"}:
                    proposal = self.service.change({
                        "request_id": request_id, "path": path,
                        "revision": self.service._source(path, source_revision)["revision"],
                        "change": changes,
                    }, today)
                    return self._proposal(
                        proposal, thread_id, today, message, allow_autoapply=allow_autoapply,
                    )
                proposal = self.service.refine({
                    "request_id": request_id, "path": path,
                    "revision": self.service._source(path, source_revision)["revision"],
                    "changes": changes,
                }, today)
            except (TaskError, SourceError) as error:
                raise TaskAssistError(str(error)) from None
            return self._proposal(
                proposal, thread_id, today, message, allow_autoapply=allow_autoapply,
            )
        if intent == "resolve" and path and self._explicit_done(message):
            completion = item["completion"]
            if not isinstance(completion, dict):
                return None
            original = message.casefold()
            result, evidence = completion["result"], completion["evidence"]
            if not result.strip() or not evidence.strip() or result.casefold() not in original or evidence.casefold() not in original:
                return None
            try:
                source = self.service._source(path, source_revision)
                proposal = self.service.close({
                    "request_id": request_id, "path": path, "revision": source["revision"],
                    "completion": {
                        "result": result, "evidence": evidence,
                        "verification": "owner", "verified_on": owner_today.isoformat(),
                        **({"learning": completion["learning"]} if completion["learning"] else {}),
                    },
                    "checked_done_when": True,
                }, today)
            except TaskError as error:
                raise TaskAssistError(str(error)) from None
            return self._proposal(proposal, thread_id, today, message)
        return None

    def _proposal(
        self, proposal: dict[str, Any], thread_id: str, today: date, message: str,
        *, allow_autoapply: bool = True,
    ) -> dict[str, Any]:
        if not isinstance(proposal, dict) or not isinstance(proposal.get("id"), str):
            raise TaskAssistError("assist_proposal_invalid")
        proposal_id = proposal["id"]
        card = {
            "type": "proposal", "kind": "proposal", "id": proposal_id, "proposal_id": proposal_id,
            "receipt_id": proposal_id,
            "digest": proposal.get("approval_digest"),
            "action_digest": proposal.get("approval_digest"),
            "approval_digest": proposal.get("approval_digest"),
            "title": proposal.get("action", {}).get("definition", {}).get("title")
            or proposal.get("action", {}).get("changes", {}).get("title")
            or "Task update",
            "status": proposal.get("status"),
            "publication_status": None,
            "source_status": "current",
            "saved": False,
            "summary": "Review this exact task change before it is saved.",
        }
        action = proposal.get("action", {})
        try:
            source = self.service._source(proposal["source_path"], proposal["source_revision"])
        except (TaskError, SourceError) as error:
            raise TaskAssistError(str(error)) from None
        original = {}
        changes = {}
        kind = proposal.get("kind")
        if action.get("kind") in {"refine_task", "update_task"}:
            changes = copy.deepcopy(action.get("changes") or action.get("change") or {})
            original = {key: source.get(key) for key in changes}
        elif kind == "capture_task":
            changes = copy.deepcopy(action.get("definition") or {})
        if task_path(proposal.get("source_path")):
            card["task"] = {"path": proposal["source_path"], "revision": proposal["source_revision"]}
            if not action.get("definition", {}).get("title"):
                card["title"] = source.get("title", card["title"])
        card["diff"] = [
            {"field": key, "before": original.get(key), "after": value}
            for key, value in changes.items()
        ]

        if kind in {"capture_task", "refine_task", "edit_task", "close_task"}:
            def save_operation(state: dict[str, Any]) -> None:
                ops = state["operations"]
                if proposal_id not in ops and len(ops) >= MAX_OPERATIONS:
                    raise TaskAssistError("assist_operation_capacity")
                ops[proposal_id] = {
                    "path": proposal["source_path"], "kind": kind,
                    "source_revision": proposal["source_revision"],
                    "created_on": today.isoformat(), "thread_id": thread_id,
                    "receipt_id": proposal_id,
                    **({"changes": changes, "original": original} if changes else {}),
                }
            self.store.update(save_operation)

        action_name = {
            "capture_task": "create", "refine_task": "refine",
            "edit_task": "change", "close_task": "close",
        }.get(kind)
        if action_name:
            card["action"] = action_name
        if not self.auto_apply or not allow_autoapply or kind in {"prepare_task", "research"}:
            return card
        card.update(type="applied", kind="applied", saved=False, undo_available=False)
        try:
            def annotate(state: dict[str, Any]) -> None:
                record = state["proposals"].get(proposal_id)
                if record and record.get("task_workspace") and record.get("approval_digest") == proposal.get("approval_digest"):
                    record["approved_by"] = "assist-standing"
            self.service.store.update(annotate)
            receipt = self.service.decide({
                "proposal_id": proposal_id, "approval_digest": proposal["approval_digest"], "decision": "approve",
            }, today)
        except Exception:
            card.update(
                status="uncertain",
                summary="Publication outcome is unknown; do not retry.",
                body="The existing receipt must be reconciled. Do not repeat or approve this action.",
            )
            return card
        status = receipt.get("status") if isinstance(receipt, dict) else None
        publish = receipt.get("publish_result") if isinstance(receipt, dict) else None
        result = receipt.get("result") if isinstance(receipt, dict) else None
        if not isinstance(publish, dict) and isinstance(result, dict):
            publish = result
        publication_status = publish.get("status") if isinstance(publish, dict) else None
        source_status = receipt.get("source_status") if isinstance(receipt, dict) else None
        card["source_status"] = source_status if source_status in _SOURCE_STATUS else "unavailable"
        card["status"] = status if status in _SAFE_STATUS else "uncertain"
        card["publication_status"] = publication_status
        confirmed = (
            status == "completed"
            and publication_status == "merged"
            and card["source_status"] == "current"
        )
        if not confirmed:
            if publication_status == "submitted":
                if self.auto_apply:
                    card.update(type="applied", kind="applied", saved=False, undo_available=False)
                card["summary"] = "Submitted, not saved yet."
            elif publication_status in {"unknown", "in_progress"} or status in {"uncertain", "unknown", "executing"}:
                card["summary"] = "Publication outcome is unknown; do not retry."
            elif publication_status == "merged":
                card.update(
                    title="Canonical source not confirmed",
                    body="The writer reported merge, but a current canonical source was not confirmed.",
                )
                card["summary"] = "Publication reported merged, but the canonical source is not confirmed current."
            else:
                card.update(
                    title="Task update not confirmed",
                    body="The existing receipt records this outcome; review it before taking another action.",
                )
            return card
        if kind == "capture_task":
            card.update(type="applied", kind="applied", undo_available=False)
        else:
            card.update(type="applied", kind="applied", undo_available=False)
        card["saved"] = True
        card["status"] = status
        card["publication_status"] = "merged"
        card["receipt_id"] = proposal_id
        card["diff"] = [
            {"field": key, "before": original.get(key), "after": value}
            for key, value in changes.items()
        ]
        card["summary"] = (
            result.get("summary") if isinstance(result, dict) and isinstance(result.get("summary"), str)
            else "Canonical task update confirmed."
        )
        applied_revision = None
        final_path = publish.get("path") if isinstance(publish, dict) else None
        final_revision = publish.get("source_revision") if isinstance(publish, dict) else None
        if isinstance(final_path, str) and task_path(final_path) and isinstance(final_revision, str):
            if re.fullmatch(r"[0-9a-f]{40}", final_revision):
                applied_revision = final_revision
                card["task"] = {"path": final_path, "revision": final_revision}
        if applied_revision is None:
            try:
                current = self.service._source(proposal["source_path"])
                applied_revision = current.get("revision")
            except (TaskError, SourceError):
                pass
        if applied_revision and proposal_id in self.store.read()["operations"]:
            def set_revision(state: dict[str, Any]) -> None:
                operation = state["operations"].get(proposal_id)
                if operation:
                    operation["applied_revision"] = applied_revision
            self.store.update(set_revision)
        if applied_revision and task_path(proposal["source_path"]):
            card.setdefault("task", {"path": proposal["source_path"], "revision": applied_revision})
        reversible = (
            set(changes) <= (set(EDIT_FIELDS) | {"deadline", "focus_on"})
            and all(value is not None or key in {"review_on", "waiting_for", "deadline", "focus_on"}
                    for key, value in original.items())
        )
        card["undo_available"] = bool(kind in _CHANGE_KIND and changes and applied_revision and reversible)
        return card

    @staticmethod
    def _cards(item: dict[str, Any], operation: dict[str, Any] | None, source: dict[str, Any] | None) -> list[dict[str, Any]]:
        if operation:
            return [operation]
        intent = item["intent"]
        if intent == "detail" and source:
            allowed = (
                "path", "revision", "title", "area", "project", "stage", "execution", "outcome",
                "next_action", "done_when", "deadline", "review_on", "waiting_for",
            )
            return [{"type": "task", "kind": "task", **{key: source[key] for key in allowed if key in source}}]
        if intent == "estimate" and item["estimate"]:
            return [{"type": "estimate", "kind": "estimate", **item["estimate"]}]
        if intent in {"plan", "execute"} and item["plan"]:
            plan = item["plan"]
            card = {
                "type": "plan", "kind": "plan", "steps": plan["steps"],
                "total_estimate_min": plan["total_estimate_min"],
            }
            next_action = (item.get("changes") or {}).get("next_action")
            if isinstance(next_action, str) and next_action:
                card["next_action"] = next_action
            return [card]
        if intent == "next" and source:
            return [{"type": "task", "kind": "task", "path": source["path"], "revision": source["revision"],
                     "title": source["title"], "next_action": source.get("next_action", "")}]
        if intent == "learn":
            return [{"type": "knowledge", "kind": "knowledge", "title": "Learning draft",
                     "target": item.get("knowledge_target") or "learning",
                     "body": item["reply"], "saved": False}]
        if intent == "resolve" and not item["completion"]:
            return [{"type": "draft", "kind": "draft", "title": "Closure needs verification",
                     "body": "Owner confirmation and exact evidence are needed before closure.",
                     "verified": False}]
        if intent == "execute":
            return [{
                "type": "draft", "kind": "draft", "title": "Execution preparation",
                "body": item["reply"], "saved": False,
            }]
        return []

    def _run(
        self, payload: dict[str, Any], today: date, *, mode: str, action: str | None,
        message: str | None = None, task_revision: str | None = None,
    ) -> dict[str, Any]:
        if not self.enabled:
            raise TaskAssistError("assist_not_configured")
        today = _date(today)
        owner_today = self._owner_today(today)
        identifier = _uuid(payload["request_id"])
        language = payload.get("language", "auto")
        if language not in LANGUAGES:
            raise TaskAssistError("assist_language_invalid")
        thread_id = payload.get("thread_id")
        if thread_id is not None:
            thread_id = _uuid(thread_id)
        task_path_value = payload.get("task_path")
        if task_path_value is not None and not task_path(task_path_value):
            raise TaskAssistError("assist_task_path_invalid")
        if task_revision is not None and (
            not isinstance(task_revision, str) or not re.fullmatch(r"[0-9a-f]{40}", task_revision)
        ):
            raise TaskAssistError("assist_task_revision_invalid")
        clean_message = _clean_message(message)
        model_name = self._model_for(mode, action, clean_message)
        digest_value = {
            "mode": mode, "action": action, "language": language,
            "thread_id": thread_id, "task_path": task_path_value, "task_revision": task_revision,
            "voice": payload.get("voice", False),
        }
        digest_value["message"] = clean_message
        digest = _safe_digest(digest_value)
        resolved_thread, cached = self._claim(
            identifier, digest, thread_id, today, voice=False, model=self.models[model_name],
        )
        if cached is not None:
            if not self._recheck_thread(resolved_thread):
                safe_response = {
                    "thread_id": resolved_thread,
                    "reply": "The task source changed, so earlier context was cleared. Please restate what you need.",
                    "language": cached.get("language", "en"), "cards": [], "suggestions": [],
                    "usage": self.usage(today),
                }
                key = request_key(identifier)

                def sanitize_cache(state: dict[str, Any]) -> None:
                    record = state["requests"].get(key)
                    if record:
                        record["response"] = copy.deepcopy(safe_response)

                self.store.update(sanitize_cache)
                return safe_response
            return cached

        try:
            if not self._recheck_thread(resolved_thread):
                raise TaskAssistError("assist_thread_context_invalidated")
            candidates = self._overview_candidates(owner_today) if task_path_value is None and (
                mode == "chat" or action == "next"
            ) else []
            item, input_tokens, output_tokens = self._generate(
                mode=mode, action=action, message=clean_message, language=language,
                thread_id=resolved_thread, today=owner_today, task_path_value=task_path_value,
                task_revision=task_revision, model=model_name, candidates=candidates,
            )
            if output_tokens > self.max_output_tokens:
                raise TaskAssistError("assist_model_usage_invalid")
            self._settle(
                identifier, today, input_tokens=input_tokens, output_tokens=output_tokens,
                model=self.models[model_name],
            )
            item["reply"] = item["reply"][:1200]
            resolved_path = task_path_value or item["task_path"]
            if task_path_value is None:
                if resolved_path is not None:
                    candidate = next((item for item in candidates if item["path"] == resolved_path), None)
                    if candidate is None:
                        raise TaskAssistError("assist_model_output_invalid")
                    task_revision = candidate["revision"]
            elif item["task_path"] not in (None, task_path_value):
                raise TaskAssistError("assist_model_output_invalid")
            else:
                item["task_path"] = task_path_value
            if item["task_path"] is None:
                item["task_path"] = resolved_path
            source = None
            if resolved_path is not None:
                try:
                    source = self.service._source(resolved_path, task_revision)
                except (TaskError, SourceError) as error:
                    raise TaskAssistError(str(error)) from None
            if item["intent"] == "resolve" and item["completion"] is not None:
                if not self._explicit_done(message):
                    item["completion"] = None
            authorized_operation = not (
                mode == "chat" and (
                    (item["intent"] == "capture" and not _EXPLICIT_CAPTURE.search(clean_message))
                    or (item["intent"] in {"execute", "change", "refine"} and not _EXPLICIT_CHANGE.search(clean_message))
                )
            )
            operation = self._operation(
                item, identifier=identifier, today=today, thread_id=resolved_thread,
                owner_today=owner_today, message=clean_message,
                intent=action or item["intent"], source_revision=task_revision,
            ) if authorized_operation else None
            response = {
                "thread_id": resolved_thread, "reply": item["reply"], "language": item["language"],
                "cards": self._cards(item, operation, source),
                "suggestions": item["suggestions"][:4],
                "usage": self.usage(today),
            }
            card_task = operation.get("task") if operation else None
            task_refs = {
                candidate["path"]: candidate["revision"]
                for candidate in candidates
            }
            if source is not None:
                task_refs[source["path"]] = source["revision"]
            if (
                isinstance(card_task, dict) and task_path(card_task.get("path"))
                and isinstance(card_task.get("revision"), str)
                and re.fullmatch(r"[0-9a-f]{40}", card_task["revision"])
            ):
                task_refs[card_task["path"]] = card_task["revision"]
            self._finish(identifier, today, resolved_thread, clean_message, response, task_refs)
            return response
        except Exception:
            self._mark_uncertain(identifier)
            raise

    def chat(self, payload: dict[str, Any], today: date) -> dict[str, Any]:
        payload = _strict_payload(
            payload, {"request_id", "message", "task"},
            {"thread_id", "language", "voice"},
        )
        if "voice" in payload and type(payload["voice"]) is not bool:
            raise TaskAssistError("assist_request_invalid")
        task_path_value, task_revision = self._selected_task(payload)
        message = _clean_message(payload["message"])
        normalized = dict(payload)
        if task_path_value is not None:
            normalized["task_path"] = task_path_value
            normalized["task_revision"] = task_revision
        return self._run(
            normalized, today, mode="chat", action=None, message=message,
            task_revision=task_revision,
        )

    def step(self, payload: dict[str, Any], today: date) -> dict[str, Any]:
        payload = _strict_payload(
            payload, {"request_id", "step", "task", "input"},
            {"thread_id", "language"},
        )
        action = payload["step"]
        if action not in INTENTS:
            raise TaskAssistError("assist_action_invalid")
        message = payload["input"]
        if message is None:
            message = {
                "next": "Show the next action for this selected task.",
                "detail": "Show the details of this selected task.",
                "estimate": "Estimate the effort for this selected task.",
                "plan": "Prepare a bounded plan for this selected task.",
                "execute": "Help prepare the next authorized step for this task.",
                "resolve": "Review whether this task can be closed.",
                "learn": "Draft a learning note for this task.",
                "capture": "Capture this explicitly selected task request.",
                "chat": "Help with this task.",
                "change": "Change the selected task as requested.",
                "refine": "Refine the selected task as requested.",
            }[action]
        normalized_payload = {
            "request_id": payload["request_id"],
            "action": action, "message": message, "task": payload["task"],
            "language": payload.get("language", "auto"),
            **({"thread_id": payload["thread_id"]} if "thread_id" in payload else {}),
        }
        payload = normalized_payload
        task_path_value, task_revision = self._selected_task(payload)
        message = _clean_message(payload["message"])
        normalized = dict(payload)
        if task_path_value is not None:
            normalized["task_path"] = task_path_value
        return self._run(
            normalized, today, mode="step", action=action, message=message,
            task_revision=task_revision,
        )

    @staticmethod
    def _selected_task(payload: dict[str, Any]) -> tuple[str | None, str | None]:
        task = payload.get("task")
        path, revision = payload.get("task_path"), payload.get("task_revision")
        if task is not None:
            if (
                not isinstance(task, dict) or set(task) != {"path", "revision"}
                or path is not None or revision is not None
            ):
                raise TaskAssistError("assist_request_invalid")
            path, revision = task["path"], task["revision"]
        if path is None:
            if revision is not None:
                raise TaskAssistError("assist_request_invalid")
            return None, None
        if not task_path(path):
            raise TaskAssistError("assist_task_path_invalid")
        if not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision):
            raise TaskAssistError("assist_task_revision_invalid")
        return path, revision

    def usage(self, today: date) -> dict[str, Any]:
        today = _date(today)
        state = self.store.read()
        ledger = state["ledger"]
        month = today.strftime("%Y-%m")
        day = today.isoformat()
        month_bucket = ledger if ledger["month"] == month else ledger.get("month_history", {}).get(month, {})
        day_bucket = ledger if ledger["day"] == day else ledger.get("day_history", {}).get(day, {})
        spent = month_bucket.get("spent_micro_eur", 0)
        reserved = month_bucket.get("reserved_micro_eur", 0)
        daily_spent = day_bucket.get("daily_spent_micro_eur", 0)
        daily_reserved = day_bucket.get("daily_reserved_micro_eur", 0)
        soft = _micro(self.daily_soft_cap)
        result = {
            "month": month, "daily_date": day, "currency": "EUR",
            "monthly_limit": float(self.monthly_budget),
            "monthly_used": spent / 1_000_000,
            "monthly_reserved": reserved / 1_000_000,
            "monthly_remaining": max(0, _micro(self.monthly_budget) - spent - reserved) / 1_000_000,
            "daily_soft_cap": soft / 1_000_000,
            "daily_used": daily_spent / 1_000_000,
            "daily_reserved": daily_reserved / 1_000_000,
            "daily_soft_cap_reached": daily_spent + daily_reserved >= soft,
            "input_tokens": month_bucket.get("input_tokens", 0),
            "output_tokens": month_bucket.get("output_tokens", 0),
        }
        result.update(
            month_eur=result["monthly_used"],
            month_cap_eur=result["monthly_limit"],
            today_eur=result["daily_used"],
            today_cap_eur=result["daily_soft_cap"],
            calls_today=sum(
                1 for request in state["requests"].values()
                if request["created_on"] == day and request["status"] in {"claimed", "recorded", "uncertain"}
            ),
            models={**self.models, "transcription": self.transcription_model},
        )
        return result

    def _receipt_poll_claim(self, request_id: str, receipt_id: str, today: date, thread_id: str) -> None:
        key = request_key(request_id)
        digest = _safe_digest({"mode": "receipt", "receipt_id": receipt_id})

        def claim(state: dict[str, Any]) -> None:
            prune_assist_state(state, today)
            previous = state["requests"].get(key)
            if previous:
                if previous["digest"] != digest:
                    raise TaskAssistError("assist_request_conflict")
                return
            if len(state["requests"]) >= MAX_REQUESTS:
                raise TaskAssistError("assist_request_capacity")
            state["requests"][key] = {
                "digest": digest, "status": "recorded", "created_on": today.isoformat(),
                "thread_id": thread_id, "response": None, "reserved_micro_eur": 0,
            }

        self.store.update(claim)

    def _refresh_operation(self, receipt_id: str, today: date) -> tuple[dict[str, Any], dict[str, Any]]:
        state = self.store.read()
        operation = state["operations"].get(receipt_id)
        if not operation:
            raise TaskAssistError("assist_receipt_invalid")
        try:
            receipt = self.service.reconcile(receipt_id, today)
        except (TaskError, SourceError) as error:
            raise TaskAssistError(str(error)) from None
        if not isinstance(receipt, dict) or receipt.get("id") != receipt_id:
            raise TaskAssistError("assist_receipt_invalid")

        publication = receipt.get("publish_result")
        result = receipt.get("result")
        if not isinstance(publication, dict) and isinstance(result, dict):
            publication = result
        publication_status = publication.get("status") if isinstance(publication, dict) else None
        source_status = receipt.get("source_status")
        source_status = source_status if source_status in _SOURCE_STATUS else "unavailable"
        status = receipt.get("status")
        status = status if status in _SAFE_STATUS else "uncertain"
        merged_current = (
            status == "completed" and publication_status == "merged" and source_status == "current"
        )
        current_source = None
        applied_revision = None
        if merged_current:
            path = publication.get("path") if isinstance(publication, dict) else None
            path = path if isinstance(path, str) and task_path(path) else operation["path"]
            revision = publication.get("source_revision") if isinstance(publication, dict) else None
            try:
                current_source = self.service._source(path, revision)
                applied_revision = current_source.get("revision")
            except (TaskError, SourceError):
                source_status = "unavailable"
                merged_current = False
        if applied_revision and re.fullmatch(r"[0-9a-f]{40}", applied_revision):
            def save_revision(state: dict[str, Any]) -> None:
                saved = state["operations"].get(receipt_id)
                if saved:
                    saved["applied_revision"] = applied_revision
            self.store.update(save_revision)
            operation["applied_revision"] = applied_revision

        changes = operation.get("changes", {})
        original = operation.get("original", {})
        action_name = {
            "capture_task": "create", "refine_task": "refine",
            "edit_task": "change", "close_task": "close",
        }.get(operation["kind"], "refine")
        reversible = (
            set(changes) <= (set(EDIT_FIELDS) | {"deadline", "focus_on"})
            and all(value is not None or key in {"review_on", "waiting_for", "deadline", "focus_on"}
                    for key, value in original.items())
        )
        card = {
            "type": "applied", "kind": "applied", "id": receipt_id,
            "proposal_id": receipt_id, "receipt_id": receipt_id, "action": action_name,
            "action_digest": receipt.get("approval_digest"),
            "approval_digest": receipt.get("approval_digest"),
            "status": status, "publication_status": publication_status,
            "source_status": source_status, "saved": bool(merged_current),
            "undo_available": bool(merged_current and reversible and changes and applied_revision),
            "title": "Task update",
            "summary": (
                "Canonical task update confirmed." if merged_current
                else "Submitted, not saved yet." if publication_status == "submitted"
                else "Publication outcome is unknown; do not retry."
                if status in {"uncertain", "unknown", "executing", "in_progress"}
                else "The existing receipt has not confirmed a current canonical task."
            ),
            "diff": [
                {"field": key, "before": original.get(key), "after": value}
                for key, value in changes.items()
            ],
        }
        if current_source is not None:
            card["title"] = current_source.get("title", "Task update")
            card["task"] = {
                "path": current_source["path"], "revision": current_source["revision"],
            }
        elif task_path(operation.get("path")):
            card["task"] = {
                "path": operation["path"], "revision": operation["source_revision"],
            }
        if isinstance(result, dict) and isinstance(result.get("summary"), str):
            card["summary"] = result["summary"] if merged_current else card["summary"]
        return receipt, card

    def receipt(self, payload: dict[str, Any], today: date) -> dict[str, Any]:
        if not self.enabled:
            raise TaskAssistError("assist_not_configured")
        payload = _strict_payload(payload, {"request_id", "receipt_id"}, set())
        request_id = _uuid(payload["request_id"])
        receipt_id = payload["receipt_id"]
        if not isinstance(receipt_id, str) or not re.fullmatch(r"[0-9a-f]{24}", receipt_id):
            raise TaskAssistError("assist_receipt_invalid")
        today = _date(today)
        operation = self.store.read()["operations"].get(receipt_id)
        if not operation:
            raise TaskAssistError("assist_receipt_invalid")
        self._receipt_poll_claim(request_id, receipt_id, today, operation["thread_id"])
        _, card = self._refresh_operation(receipt_id, today)
        return {
            "thread_id": operation["thread_id"],
            "reply": card["summary"], "language": "en",
            "cards": [card], "suggestions": [], "usage": self.usage(today),
        }

    def voice(self, audio: bytes, mime: str, request_id: str, today: date, **options: Any) -> dict[str, Any]:
        if not options.keys() <= {"language"}:
            raise TaskAssistError("assist_request_invalid")
        if not self.enabled:
            raise TaskAssistError("assist_not_configured")
        if not isinstance(audio, bytes) or not 0 < len(audio) <= MAX_VOICE_BYTES or mime not in VOICE_MIMES:
            raise TaskAssistError("assist_audio_invalid")
        if self.transcribe is None:
            raise TaskAssistError("assist_transcription_not_configured")
        try:
            from assist_audio import audio_duration
        except ImportError:
            raise TaskAssistError("assist_transcription_not_configured") from None
        try:
            duration = audio_duration(audio, mime)
        except Exception as error:
            code = str(error)
            if code in {"assist_audio_invalid", "assist_audio_too_long"}:
                raise TaskAssistError(code) from None
            raise TaskAssistError("assist_audio_invalid") from None
        if not isinstance(duration, (int, float)) or not math.isfinite(float(duration)) or not 0 < duration <= 120:
            raise TaskAssistError("assist_audio_too_long" if isinstance(duration, (int, float)) and duration > 120 else "assist_audio_invalid")
        today = _date(today)
        identifier = _uuid(request_id)
        language = options.get("language", "auto")
        if language not in LANGUAGES:
            raise TaskAssistError("assist_language_invalid")
        payload = {
            "request_id": identifier, "language": language,
        }
        payload = _strict_payload(payload, {"request_id"}, {"language"})
        digest = _safe_digest({
            "mode": "voice-transcribe", "audio_sha256": hashlib.sha256(audio).hexdigest(),
            "mime": mime, "language": language,
        })
        resolved_thread, cached = self._claim(
            identifier, digest, None, today, voice=True,
            audio_seconds=float(duration), create_thread=False,
        )
        if cached is not None:
            return cached
        try:
            try:
                transcription = self.transcribe(audio, mime)
            except (TaskAssistError, TaskError):
                raise
            except Exception as error:
                log.warning("task assist transcription failed error=%s", type(error).__name__)
                raise TaskAssistError("assist_transcription_unavailable") from None
            if not isinstance(transcription, dict) or set(transcription) - {
                "text", "language", "duration_s", "usage",
            } or not isinstance(transcription.get("text"), str):
                raise TaskAssistError("assist_transcription_invalid")
            text = transcription["text"]
            if not text.strip() or len(text) > MAX_INPUT_CHARS:
                raise TaskAssistError("assist_transcription_invalid")
            transcription_language = transcription.get("language") or language
            if (
                not isinstance(transcription_language, str) or len(transcription_language) > 16
                or not re.fullmatch(r"[a-z]{2,3}(?:-[A-Za-z0-9]{2,8})*", transcription_language)
            ):
                raise TaskAssistError("assist_transcription_invalid")
            token_usage = transcription.get("usage")
            if token_usage is None:
                input_tokens, output_tokens = 0, 0
            elif isinstance(token_usage, dict) and (
                token_usage.get("input_tokens") is None or token_usage.get("output_tokens") is None
            ):
                input_tokens, output_tokens = 0, 0
            else:
                input_tokens, output_tokens = _usage(token_usage)
            self._settle(
                identifier, today, input_tokens=input_tokens, output_tokens=output_tokens,
                billed_input_tokens=0, billed_output_tokens=0,
                audio_seconds=float(duration),
            )
            response = {
                "text": text, "language": transcription_language, "duration_s": float(duration),
            }
            self._finish_voice(identifier)
            return response
        except Exception:
            self._mark_uncertain(identifier)
            raise

    def undo(self, payload: dict[str, Any], today: date) -> dict[str, Any]:
        if not self.enabled:
            raise TaskAssistError("assist_not_configured")
        payload = _strict_payload(payload, {"request_id", "receipt_id"}, set())
        request_id = _uuid(payload["request_id"])
        receipt_id = payload["receipt_id"]
        if not isinstance(receipt_id, str) or not re.fullmatch(r"[0-9a-f]{24}", receipt_id):
            raise TaskAssistError("assist_receipt_invalid")
        today = _date(today)
        operation = self.store.read()["operations"].get(receipt_id)
        digest = _safe_digest({"mode": "undo", "receipt_id": receipt_id})
        thread_id, cached = self._claim_deterministic(
            request_id, digest, today, operation.get("thread_id") if operation else None,
        )
        if cached is not None:
            return self._cached_thread_response(request_id, thread_id, cached, today)
        if not operation or operation["kind"] not in _CHANGE_KIND:
            response = {
                "undone": False, "receipt_id": receipt_id, "thread_id": thread_id,
                "reply": "This task change cannot be undone automatically.",
                "language": "en", "cards": [{
                    "kind": "draft", "type": "draft", "title": "Undo unavailable",
                    "body": "Only source-version-bound task changes can be undone; task creation is retained.",
                }],
                "suggestions": [], "usage": self.usage(today),
            }
            self._finish_deterministic(request_id, response)
            return response
        if not operation.get("applied_revision"):
            self._refresh_operation(receipt_id, today)
            operation = self.store.read()["operations"].get(receipt_id)
        if not operation or not operation.get("applied_revision"):
            response = {
                "undone": False, "receipt_id": receipt_id, "thread_id": thread_id,
                "reply": "Undo is unavailable until the canonical change is confirmed.",
                "language": "en", "cards": [{
                    "kind": "draft", "type": "draft", "title": "Undo unavailable",
                    "body": "The original change has no confirmed current source revision.",
                }],
                "suggestions": [], "usage": self.usage(today),
            }
            self._finish_deterministic(request_id, response)
            return response
        try:
            source = self.service._source(operation["path"], operation["applied_revision"])
        except (TaskError, SourceError):
            self._mark_uncertain(request_id)
            raise TaskAssistError("task_source_changed") from None
        original = operation.get("original", {})
        changes = operation.get("changes", {})
        inverse = {key: original.get(key) for key in changes}
        if any(
            value is None and key not in {"review_on", "waiting_for", "deadline", "focus_on"}
            for key, value in inverse.items()
        ):
            response = {
                "undone": False, "receipt_id": receipt_id, "thread_id": thread_id,
                "reply": "The previous value is not available for a safe inverse.",
                "language": "en", "cards": [{
                    "kind": "draft", "type": "draft", "title": "Undo unavailable",
                    "body": "The prior canonical value was not recorded.",
                }],
                "suggestions": [], "usage": self.usage(today),
            }
            self._finish_deterministic(request_id, response)
            return response
        try:
            if len(inverse) == 1 and next(iter(inverse)) in {"deadline", "focus_on", "review_on"}:
                field, value = next(iter(inverse.items()))
                result = self.service.change({
                    "request_id": request_id.replace("-", ""), "path": source["path"],
                    "revision": source["revision"], "change": {field: value},
                }, today)
            else:
                result = self.service.refine({
                    "request_id": request_id.replace("-", ""), "path": source["path"],
                    "revision": source["revision"], "changes": inverse,
                }, today)
            card = self._proposal(result, thread_id, today, "Undo the previous task change.")
            response = {
                "undone": card.get("kind") == "applied", "receipt_id": receipt_id,
                "thread_id": thread_id, "reply": "Prepared the source-version-bound inverse change.",
                "language": "en", "cards": [card], "suggestions": [], "usage": self.usage(today),
            }
            self._finish_deterministic(
                request_id, response,
                ({"path": card["task"]["path"], "revision": card["task"]["revision"]}
                 if isinstance(card.get("task"), dict) else None),
            )
            return response
        except Exception:
            self._mark_uncertain(request_id)
            raise

    def change(self, payload: dict[str, Any], today: date) -> dict[str, Any]:
        """Prepare and optionally apply one explicit board stage transition without a model call."""
        if not self.enabled:
            raise TaskAssistError("assist_not_configured")
        payload = _strict_payload(payload, {"request_id", "path", "revision", "change"}, set())
        identifier = _uuid(payload["request_id"])
        path, revision, change = payload["path"], payload["revision"], payload["change"]
        if (
            not task_path(path) or not isinstance(revision, str) or not re.fullmatch(r"[0-9a-f]{40}", revision)
            or not isinstance(change, dict) or set(change) != {"stage"}
            or not isinstance(change["stage"], str)
            or change["stage"] not in {"ready", "doing", "waiting", "verify"}
        ):
            raise TaskAssistError("assist_change_invalid")
        today = _date(today)
        digest = _safe_digest({
            "mode": "change", "path": path, "revision": revision, "change": change,
        })
        thread_id, cached = self._claim_deterministic(identifier, digest, today)
        if cached is not None:
            return self._cached_thread_response(identifier, thread_id, cached, today)
        try:
            source = self.service._source(path, revision)
            proposal = self.service.change({
                "request_id": identifier.replace("-", ""), "path": path,
                "revision": source["revision"], "change": change,
            }, today)
            card = self._proposal(proposal, thread_id, today, "Update task stage.")
            response = {
                "thread_id": thread_id, "cards": [card], "usage": self.usage(today),
            }
            self._finish_deterministic(
                identifier, response,
                ({"path": card["task"]["path"], "revision": card["task"]["revision"]}
                 if isinstance(card.get("task"), dict) else None),
            )
            return response
        except Exception:
            self._mark_uncertain(identifier)
            raise
