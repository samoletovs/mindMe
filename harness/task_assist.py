def _nullable_required(properties: dict[str, Any]) -> dict[str, Any]:
    result = {}
    for key, value in properties.items():
        item = copy.deepcopy(value)
        kind = item.get("type")
        if isinstance(kind, str):
            item["type"] = [kind, "null"]
        if isinstance(item.get("enum"), list) and None not in item["enum"]:
            item["enum"].append(None)
        result[key] = item
    return result


